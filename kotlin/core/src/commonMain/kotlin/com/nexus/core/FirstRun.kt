package com.nexus.core

/**
 * 첫 연결·첫 동기화 대기 판정 (#213, E14-3) — 첫날의 0 데이터를 '고장'이 아니라 '준비 중'으로.
 *
 * 헬스 연동 앱의 최대 첫세션 이탈 트리거는 "오늘 5천보를 걸었는데 앱은 0보"다. 삼성헬스 → Health
 * Connect 전파에 30~60분이 걸리므로(불변식 ⑤) 첫 진입에서 0이 보이는 건 **정상**인데, 화면이
 * 0을 나열하면 사용자는 앱이 고장 났다고 판단한다.
 *
 * ## 판정 신호를 `lastSync`에서 '손에 든 데이터'로 바꾼 이유 (#213 리뷰)
 *
 * 원래 완료 기준은 `평생 XP == 0 && lastSync == 0`이었다. 그런데 `lastSync`는 "동기화가 **돌았다**"이지
 * "데이터가 **왔다**"가 아니다. 온보딩 연결 직후 주기 워커가 곧바로 첫 실행을 하고 0건을 받아도
 * `lastSync`를 갱신한다 — 이 빈 상태는 몇 초 만에 꺼지고, 정작 겨냥한 30~60분 전파 구간 내내
 * 사용자는 다시 '0 나열'을 보게 된다. 지키려던 순간을 못 지키는 조건이었다.
 *
 * 대신 **보여줄 게 하나라도 있는가**를 본다. 완료 기준의 안전 규칙("XP>0이면 절대 미노출")은 그대로
 * 지키면서, 걸음만 있고 XP는 0인 사용자(걸음은 XP를 만들지 않는다)에게 실데이터를 숨기던 문제까지
 * 함께 막는다.
 */
object FirstRun {
    /**
     * 아직 첫 데이터를 기다리는 중인가 — **평생 원장 XP가 0이고, 표시할 건강 데이터도 없을 때만** true.
     *
     * @param lifetimeXp 평생 누적(상한 적용) 원장 XP. 0 이하 = 아직 아무것도 적립되지 않음.
     * @param hasAnyHealthData 화면이 실제로 읽어 온 창에 걸음이나 운동 세션이 하나라도 있는가.
     *   있으면 보여줄 게 있다는 뜻이므로 빈 상태를 띄우지 않는다 — 실데이터를 가리는 건 최악이다.
     */
    fun isAwaitingFirstData(lifetimeXp: Int, hasAnyHealthData: Boolean): Boolean = lifetimeXp <= 0 && !hasAnyHealthData
}
