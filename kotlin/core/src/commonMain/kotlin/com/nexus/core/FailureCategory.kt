package com.nexus.core

/**
 * 처리된-실패 분류 (#239, E15-11) — **원격으로 보낼 수 있는 진단 신호의 전부**다.
 *
 * 알파 최대 관측성 구멍이 여기였다. 동기화·화면 로드·백업의 catch가 전부 `Log.w`로 logcat에만
 * 흘렀는데, 원격 테스터 폰에선 USB 없이 볼 수 없다. Sentry는 **미처리 크래시만** 잡으므로
 * "동기화가 3일째 원장 DB 오류로 실패 중" 같은 **저하된 성공**은 2인 팀에게 완전히 보이지 않았다.
 * 알파의 목적이 학습인데 저하 실패가 안 보이면 그 학습이 유실된다.
 *
 * ## 이름이 곧 페이로드다
 *
 * 보내는 건 **이 enum의 이름 하나뿐**이다. 예외 메시지·스택·수치는 싣지 않는다 — 메시지에는
 * `"steps=8432"` 같은 값이 섞일 수 있고(불변식 ②), 스택은 처리된 실패엔 과하다. 그래서 새 신호를
 * 추가하려면 여기 상수를 늘려야 하고, 그 목록은 테스트로 고정된다(`FailureCategoryTest`).
 *
 * 이름 자체가 건강 항목을 가리켜서도 안 된다 — [HealthTermDenylist]로 검사한다.
 */
enum class FailureCategory {
    /** 동기화 중 I/O 실패 — 네트워크·파일. 재시도 대상. */
    SYNC_IO,

    /** Health Connect 서비스와의 IPC 실패(서비스 사망·업데이트 중). 재시도 대상. */
    SYNC_REMOTE,

    /** 권한 회수로 동기화 불가 — 재시도해도 소용없다. 사용자 조치가 필요한 유일한 분류. */
    SYNC_PERMISSION,

    /** 원장 DB 문제(디스크 꽉 참·손상). crown jewel이 걸린 신호라 가장 무겁다. */
    LEDGER_DB,

    /**
     * 원장이 자기 불변식을 위반했다 ([LedgerIntegrity], #245) — DB는 정상인데 **내용이 깨진** 경우.
     *
     * [LEDGER_DB]와 분리한 이유: DB 오류는 재시도·디스크 정리로 풀리지만 이건 이미 박제된 행의
     * 문제라 사용자가 할 수 있는 게 없다. 우리가 코드를 고쳐야 하는 신호다. 어떤 위반인지는
     * 싣지 않는다 — 분류 이름 하나가 페이로드 전부다.
     */
    LEDGER_INTEGRITY,

    /** 백업 가져오기 실패 — 손상 파일·미지원 버전. */
    BACKUP_IMPORT,

    /** 홈 화면 로드 실패 — 사용자는 재시도 안내를 본다(#227). */
    HOME_LOAD,

    /** 활동 화면 로드 실패. */
    ACTIVITY_LOAD,

    /** 성장 화면 로드 실패. */
    GROWTH_LOAD,
}
