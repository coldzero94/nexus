package com.nexus.core

/**
 * 평생 누적 신호 (#113, E5-13) — **원장이 유일한 소스**다.
 *
 * ## 왜 원장인가
 *
 * 평생 지표는 "앱을 쓴 전 기간"을 말하는데, Health Connect 읽기는 창(워커 7일·화면 28일)으로
 * 제한돼 있고 과거로 무한정 거슬러 올라갈 수도 없다. 원장은 append-only라 첫날부터의 기록을
 * 그대로 갖고 있고, 값이 **줄어들지 않는다**(불퇴행 불변식과 같은 성질).
 *
 * ## 왜 걸음·거리 마일스톤이 없는가
 *
 * 티켓(#113)은 "총 걸음 100km"를 예로 들었지만 **원장에 원시 건강 수치를 담지 않는다**(제품 불변식).
 * 담으면 그 순간 원장이 건강 데이터 저장소가 되고, 백업·서버 확장에서 전부 걸린다. 그래서 평생 축은
 * 원장이 실제로 아는 것 — **함께한 날 수와 성장의 총량** — 으로 세운다. '내 기록의 거울'이라는
 * 컨셉에는 오히려 이쪽이 가깝다.
 */
object LifetimeSignals {

    /**
     * 활동한 날 수 — 일별 순 XP가 **양수**인 날만 센다.
     *
     * 취소(보상 이벤트)로 하루가 통째로 상쇄되면 그날은 활동일이 아니다. 합이 0 이하인 날을 세면
     * 삭제된 기록이 영원히 남아 "함께한 100일"이 거짓이 된다.
     *
     * @param dailyNetXp 원장의 일자별 순 XP 합(취소 반영). 순서는 무관하다.
     */
    fun activeDays(dailyNetXp: Map<Long, Int>): Int = dailyNetXp.count { it.value > 0 }
}
